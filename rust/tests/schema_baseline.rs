//! The schema Rust creates (rust/schema/baseline.sql, queue_baseline.sql) is the one Rails builds
//! (script/rust/prepare_install.rb), compared after this build's Rust migrations on both primaries (PLAN-B1 §7 T1).
//! `B1_REGENERATE=1` rewrites both files from the Rails-built databases and fails, so the result is reviewed and
//! committed; CI never sets it. Plus: no Rust migration adds an object to, or rebuilds, a table baseline.sql creates.
mod common;
use deltabadger::store;
use rusqlite::{types::Value, Connection};
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

type Rows = Vec<Vec<Value>>;

fn ident(name: &str) -> String { format!("\"{}\"", name.replace('"', "\"\"")) }
fn lit(text: &str) -> String { format!("'{}'", text.replace('\'', "''")) }

fn rows(c: &Connection, sql: &str) -> Rows {
    let mut st = c.prepare(sql).unwrap_or_else(|e| panic!("{sql}: {e}"));
    let n = st.column_count();
    st.query_map([], |r| (0..n).map(|i| r.get::<_, Value>(i)).collect()).unwrap().map(Result::unwrap).collect()
}

fn texts(c: &Connection, sql: &str) -> Vec<String> {
    c.prepare(sql).unwrap().query_map([], |r| r.get(0)).unwrap().map(Result::unwrap).collect()
}

fn tables(c: &Connection) -> Vec<String> { texts(c, "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name") }

/// baseline.sql from a Rails-built database: its statements in Rails' rowid order (SQLite makes sqlite_sequence and the
/// autoindexes itself), then the rows Rails wrote, `environment` as production writes it and no schema_sha1
/// (D-BOOT-NO-SCHEMA-SHA1). Any other row is new to this generator and stops it; T1 compares every row anyway.
fn generate(rails: &Connection) -> String {
    let mut out = String::from("-- Generated by rust/tests/schema_baseline.rs (B1_REGENERATE=1) from the database Rails builds; do not edit.\n\
        -- store::create_schema / create_queue_schema run it in one transaction. No schema_sha1 row: D-BOOT-NO-SCHEMA-SHA1.\n");
    let statements = "SELECT sql FROM sqlite_master WHERE name <> 'sqlite_sequence' AND substr(name, 1, 17) <> 'sqlite_autoindex_' ORDER BY rowid";
    for sql in texts(rails, statements) { out += &format!("{sql};\n"); }
    for row in rows(rails, "SELECT name, seq FROM sqlite_sequence ORDER BY rowid") {
        let (Value::Text(name), Value::Integer(seq)) = (&row[0], &row[1]) else { panic!("sqlite_sequence row {row:?}") };
        out += &format!("INSERT INTO sqlite_sequence (name, seq) VALUES ({}, {seq});\n", lit(name));
    }
    for version in texts(rails, "SELECT version FROM schema_migrations ORDER BY rowid") {
        out += &format!("INSERT INTO schema_migrations (version) VALUES ({});\n", lit(&version));
    }
    for key in texts(rails, "SELECT key FROM ar_internal_metadata ORDER BY rowid") {
        match key.as_str() {
            "environment" => out += "INSERT INTO ar_internal_metadata (key, value, created_at, updated_at) VALUES \
                ('environment', 'production', strftime('%Y-%m-%d %H:%M:%f', 'now'), strftime('%Y-%m-%d %H:%M:%f', 'now'));\n",
            "schema_sha1" => {}
            other => panic!("ar_internal_metadata has a row this generator doesn't know: {other}"),
        }
    }
    let unknown: Vec<String> = tables(rails).into_iter()
        .filter(|t| !["sqlite_sequence", "schema_migrations", "ar_internal_metadata"].contains(&t.as_str()))
        .filter(|t| rails.query_row(&format!("SELECT count(*) FROM {}", ident(t)), [], |r| r.get::<_, i64>(0)).unwrap() > 0).collect();
    assert!(unknown.is_empty(), "Rails wrote rows this generator doesn't replay, in {unknown:?}");
    out
}

/// Everything T1 compares, by section, so a difference names its table.
fn snapshot(c: &Connection) -> BTreeMap<String, Rows> {
    let mut s = BTreeMap::new();
    // By (type, name), not rowid: Rails rebuilds tables for their foreign keys, so its rowid order differs.
    s.insert("sqlite_master".into(), rows(c, "SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY type, name"));
    for pragma in ["journal_mode", "page_size", "auto_vacuum", "encoding", "user_version", "application_id"] {
        s.insert(format!("pragma {pragma}"), rows(c, &format!("PRAGMA {pragma}")));
    }
    for t in tables(c) {
        let arg = lit(&t);
        s.insert(format!("{t}: table_xinfo"), rows(c, &format!("SELECT * FROM pragma_table_xinfo({arg})")));
        s.insert(format!("{t}: index_list"), rows(c, &format!("SELECT * FROM pragma_index_list({arg})")));
        s.insert(format!("{t}: foreign_key_list"), rows(c, &format!("SELECT * FROM pragma_foreign_key_list({arg})")));
        for index in texts(c, &format!("SELECT name FROM pragma_index_list({arg})")) {
            s.insert(format!("{t}: index_xinfo {index}"), rows(c, &format!("SELECT * FROM pragma_index_xinfo({})", lit(&index))));
        }
        // applied_at is Utc::now; ar_internal_metadata's value and timestamps depend on the RAILS_ENV and the clock.
        let select = match t.as_str() {
            "rust_schema_migrations" => "rowid, version",
            "ar_internal_metadata" => "rowid, key",
            _ => "rowid, *",
        };
        s.insert(format!("{t}: rows"), rows(c, &format!("SELECT {select} FROM {} ORDER BY rowid", ident(&t))));
    }
    s
}

/// The id one plain insert into each table gets (AUTOINCREMENT tables continue from sqlite_sequence, the others from
/// max(rowid)). Every column but the rowid alias gets a dummy value; CHECKs and foreign keys are off for it.
fn next_ids(c: &Connection) -> BTreeMap<String, i64> {
    c.execute_batch("PRAGMA ignore_check_constraints = ON; PRAGMA foreign_keys = OFF").unwrap();
    tables(c).into_iter().filter(|t| !t.starts_with("sqlite_")).map(|t| {
        let mut st = c.prepare(&format!("SELECT name, type, pk, hidden FROM pragma_table_xinfo({})", lit(&t))).unwrap();
        let cols: Vec<(String, String, i64, i64)> = st.query_map([], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?))).unwrap().map(Result::unwrap).collect();
        let keys = cols.iter().filter(|col| col.2 > 0).count();
        let given: Vec<String> = cols.iter()
            .filter(|(_, ty, pk, hidden)| *hidden == 0 && !(keys == 1 && *pk == 1 && ty.eq_ignore_ascii_case("INTEGER")))
            .map(|col| ident(&col.0)).collect();
        let sql = if given.is_empty() { format!("INSERT INTO {} DEFAULT VALUES", ident(&t)) } else {
            format!("INSERT INTO {} ({}) VALUES ({})", ident(&t), given.join(", "), vec!["'b1-next-id'"; given.len()].join(", "))
        };
        c.execute(&sql, []).unwrap_or_else(|e| panic!("{sql}: {e}"));
        (t, c.last_insert_rowid())
    }).collect()
}

/// Rails' file vs the same file built by `create`, Rust migrations applied to both when `migrate`.
fn rust_equals_rails(file: &str, baseline: &str, create: fn(&Connection) -> rusqlite::Result<()>, migrate: bool) {
    let rails_dir = common::rails_install_unmigrated();
    let rails = Connection::open(rails_dir.path().join(file)).unwrap();
    if std::env::var("B1_REGENERATE").is_ok_and(|v| v == "1") {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("schema").join(baseline);
        std::fs::write(&path, generate(&rails)).unwrap();
        panic!("B1_REGENERATE=1: rewrote {}; review and commit it, then run without B1_REGENERATE", path.display());
    }
    let rust_dir = tempfile::tempdir().unwrap();
    let rust = Connection::open(rust_dir.path().join(file)).unwrap();
    create(&rust).expect("the baseline executes on an empty file");
    if migrate {
        store::test_support::migrate(&rails).unwrap();
        store::test_support::migrate(&rust).unwrap();
    }

    let (r, s) = (snapshot(&rails), snapshot(&rust));
    assert_eq!(r.keys().collect::<Vec<_>>(), s.keys().collect::<Vec<_>>(), "{file}: different tables or indexes");
    for (section, rails_rows) in &r {
        assert_eq!(rails_rows, &s[section], "{file}: {section} differs (left Rails, right Rust)");
    }
    let env: String = rust.query_row("SELECT value FROM ar_internal_metadata WHERE key = 'environment'", [], |r| r.get(0)).unwrap();
    assert_eq!(env, "production", "{file}: Rust writes what a production db:prepare writes");
    assert_eq!(next_ids(&rails), next_ids(&rust), "{file}: the next id of each table (left Rails, right Rust)");
}

#[test]
fn the_rust_primary_is_the_rails_primary_after_the_rust_migrations() {
    rust_equals_rails("production.sqlite3", "baseline.sql", store::create_schema, true);
    let c = Connection::open_in_memory().unwrap();
    store::create_schema(&c).unwrap();
    let frozen: Vec<String> = include_str!("../schema/rails_versions.txt").lines().map(String::from).collect();
    assert_eq!(texts(&c, "SELECT version FROM schema_migrations ORDER BY version"), frozen, "the 123 frozen Rails versions");
}

#[test]
fn the_rust_queue_is_the_rails_queue() {
    rust_equals_rails("production_queue.sqlite3", "queue_baseline.sql", store::create_queue_schema, false);
}

/// Every object (table, index, trigger) by the table it belongs to, for the tables baseline.sql creates.
fn objects_of_baseline_tables(c: &Connection, baseline_tables: &BTreeSet<String>) -> BTreeMap<String, Rows> {
    let mut by_table: BTreeMap<String, Rows> = baseline_tables.iter().map(|t| (t.clone(), Vec::new())).collect();
    for row in rows(c, "SELECT tbl_name, type, name, sql FROM sqlite_master ORDER BY tbl_name, type, name") {
        let Value::Text(table) = &row[0] else { unreachable!() };
        if let Some(objects) = by_table.get_mut(table) { objects.push(row[1..].to_vec()); }
    }
    by_table
}

/// The baseline, this build's Rust migrations, then `extra`: Err names each baseline table whose objects changed.
fn baseline_tables_untouched(extra: &[(String, String, String)]) -> Result<(), String> {
    let c = Connection::open_in_memory().unwrap();
    store::create_schema(&c).unwrap();
    let baseline_tables: BTreeSet<String> = texts(&c, "SELECT tbl_name FROM sqlite_master").into_iter().collect();
    assert!(baseline_tables.contains("bots"), "baseline.sql creates the Rails tables");
    let before = objects_of_baseline_tables(&c, &baseline_tables);
    store::test_support::migrate(&c).unwrap();
    for (_, _, sql) in extra { c.execute_batch(sql).unwrap(); }
    let after = objects_of_baseline_tables(&c, &baseline_tables);
    let changed: Vec<String> = before.iter().filter(|(t, objects)| after[*t] != **objects)
        .map(|(t, objects)| format!("{t}: baseline {objects:?}, now {:?}", after[t])).collect();
    if changed.is_empty() { Ok(()) } else { Err(changed.join("\n")) }
}

#[test]
fn no_rust_migration_adds_to_or_rebuilds_a_table_the_baseline_creates() {
    baseline_tables_untouched(&[]).unwrap();
}

#[test]
fn a_migration_adding_an_index_or_a_trigger_to_a_baseline_table_is_caught() {
    for (dir, object) in [("rust_migrations_bots_index", "probe_index_on_bots"), ("rust_migrations_bots_trigger", "probe_trigger_on_bots")] {
        let extra = store::test_support::load(&Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures").join(dir)).unwrap();
        assert_eq!(extra.len(), 1, "{dir}");
        let err = baseline_tables_untouched(&extra).expect_err(dir);
        assert!(err.starts_with("bots: ") && err.contains(object) && !err.contains('\n'), "{dir}: only bots, naming {object}:\n{err}");
    }
}
